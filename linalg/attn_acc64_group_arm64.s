// per (query g, key-pair kp), lane = key within the pair, index = g*4+kp,
// kp=0..3 covering keys (0,1)(2,3)(4,5)(6,7) — the same per-query accumulator
// convention attn_acc64_arm64.s's qkAcc64NEON16 already uses (one register
// per key-pair, lane = key), replicated across G queries instead of G=1.
//
// Per d-quad, per key-pair: K is loaded and widened ONCE (4 registers,
// V24/V25/V26/V27 — see the in-place-reuse comments inline; NOT V16-19,
// because those numbers collide with accumulator indices g=4's four
// key-pairs, acc(4,kp)=16..19, which would clobber a live accumulator with a
// raw K load mid-block) and shared across all 6 queries' FMLA chains — the
// entire point of grouping, same identity argument matmul_qk_acc64_group.go's
// header already makes (only the loop NESTING changes; each (g,key)
// accumulator still receives the exact d-ascending fold MatmulQKAcc64 would
// compute for that head alone). q is re-widened per (kp, g) into 2 transient
// registers (V28/V29, same in-place trick as the K side) — 4x redundant
// across the 4 key-pairs, deliberately: q is tiny (one hd-wide row, stays
// L1-resident) so cheaply re-deriving it 4x is a better trade than spilling
// widened-K to make room for 6 simultaneously-resident widened-q rows, which
// the register count does not allow. TestQKAcc64NEON8G6_matchesGo is the
// check for the whole thing, not just the argument.
//
// Q, K, and dst pointer bookkeeping: 8 K row pointers and 6 q row pointers
// are (re)derived by chained ADD at the top of every block (K rows advance
// via the load's own post-increment through a block's d-quad sweep; q rows
// only advance once per d-quad, by an explicit ADD after the key-pair×query
// unrolled body, since the SAME q address is read 4x — once per key-pair —
// within one d-quad). dst is [G,N] row-major (unlike AV's [G,hd]): R22 tracks
// this block's query-0 COLUMN offset and is left unmodified through the
// store phase (only R26, a disposable copy, walks the 6 query rows), so
// R22+32 is the next block's column offset without any rewind arithmetic.
//
