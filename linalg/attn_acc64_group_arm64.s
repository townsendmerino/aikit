// NEON f64 G=6 grouped ports of the acc64 attention kernels (R13, goinfer's
// docs/tasks/red-october.md). G=6 is the 1.5B's real GQA group size, the
// brief's own registered decision shape; other G fall back to the plain Go
// MatmulAVAcc64Group/MatmulQKAcc64Group (see attn_acc64_group_arm64.go).
//
// avAcc64NEON8G6 — one 8-dim block of V, all G=6 queries' scores at once:
//   dst[g][d] = float32(Σ_s float64(scores[g][s]) · float64(V[s][d])),
//   key-ascending, d = 0..7 within this block.
// qkAcc64NEON8G6 — see attn_acc64_group_arm64.s's second half (appended once
// built and gated the same way).
//
// REGISTER BUDGET (red-october.md's own analysis): "AV at 8 dims × G=6 is 24
// accumulators + 4 V + 1 score = 29" of NEON's 32. V0-V23 hold the 24
// accumulators (one f64x2 register per (query g, dim-pair dp), lane = dim
// within the pair, index = g*4+dp, dp=0..3 covering dims (0,1)(2,3)(4,5)(6,7)
// of this block) — this is the SAME per-query accumulator convention
// attn_acc64_arm64.s's avAcc64NEON32 already uses (one register per dim-pair,
// lane = dim), just replicated across G queries instead of G=1. V26-V29 hold
// the block's V row widened once per key (4 registers, shared read for the
// whole g loop — the entire point of grouping, matching the identity
// argument matmul_av_acc64_group.go's header already makes: only the loop
// NESTING changes, key-ascending order per (g,dim) is unchanged). V31 holds
// one query's score widened per (key, g) — same scalar-widen convention
// avAcc64NEON32 already uses. V24, V25, V30 are unused (29 of 32 in use,
// matching the brief's own count).
//
// BIT-IDENTICAL to MatmulAVAcc64Group / to G separate MatmulAVAcc64 calls, by
// the same "order of operations applied to ONE accumulator, not what
// unrelated accumulators do in between" argument attn_acc64_arm64.s's own
// header already makes, now applied across queries instead of just across
// dims: each (g, dim) accumulator here receives exactly the same
// key-ascending fold MatmulAVAcc64 would compute for that head alone.
// TestAVAcc64NEON8G6_matchesGo is the check.
//
// No zip needed here (unlike QK's key-interleaving) — each register's two f64
// lanes are two CONSECUTIVE dims of the SAME key, not two different keys, so
// V's raw f32 quad widens directly via FCVTL (lower 2) / FCVTL2 (upper 2),
// including in place (Vd==Vn is architecturally valid for a single
// convert — the source read completes before the result is written).
//
// Encodings, same convention as attn_acc64_arm64.s (its own header has the
// full derivation and worked checks):
//   FCVTL   Vd.2D, Vn.2S            = 0x0E617800 | Rn<<5 | Rd
//   FCVTL2  Vd.2D, Vn.4S            = 0x4E617800 | Rn<<5 | Rd
//   FCVTN   Vd.2S, Vn.2D            = 0x0E616800 | Rn<<5 | Rd
//   FCVTN2  Vd.4S, Vn.2D            = 0x4E616800 | Rn<<5 | Rd
//   FMLA    Vd.2D, Vn.2D, Vm.D[i]   = 0x4FC01000 | M<<20 | Rm<<16 | i<<11 | Rn<<5 | Rd
//     (M=1, Rm&0xF in the Rm field, when the by-element source is V16-V31)
// Generated by a small Python encoder (scratchpad/gen_av.py this session) to
// avoid hand hex arithmetic; spot-checked by hand against the formulas above.

